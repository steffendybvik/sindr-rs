#!/usr/bin/env python3
"""Generate llms-full.txt: everything an LLM needs to write code against sindr.

Concatenates the READMEs, LIMITATIONS.md, the documented public API of both
crates (doc comments plus signatures, extracted from the sources) and the
examples. CI regenerates it and fails if the committed copy differs, so it
can't drift from the code.

    python3 scripts/gen_llms_full.py           # rewrite llms-full.txt
    python3 scripts/gen_llms_full.py --check   # exit 1 if it is stale
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "llms-full.txt"

# Items whose whole body is API (fields, variants), printed in full.
BODY_ITEM = re.compile(r"^(pub )(struct|enum|trait) ")
# Items printed as a signature only.
SIG_ITEM = re.compile(r"^\s*pub (fn|const|static|type|mod|use) ")
IMPL = re.compile(r"^impl\b")


def strip_tests(lines):
    """Drop everything from the unit-test module on."""
    for i, line in enumerate(lines):
        if line.startswith("#[cfg(test)]"):
            return lines[:i]
    return lines


def signature(lines, i):
    """The item starting at line i, up to its body or terminating `;`."""
    out = []
    for line in lines[i:]:
        if line.rstrip().endswith(";"):
            out.append(line)
            break
        if "{" in line:
            out.append(line[: line.index("{")].rstrip() + " { … }")
            break
        out.append(line)
    return out


def body(lines, i):
    """A column-0 item through its closing `}` (or `;` for a unit struct)."""
    out = []
    for line in lines[i:]:
        out.append(line)
        if line == "}" or (len(out) == 1 and line.rstrip().endswith(";")):
            break
    return out


def api(path):
    """Crate/module docs and documented public items of one source file."""
    lines = strip_tests(path.read_text().splitlines())
    module_docs = [l[3:].removeprefix(" ") for l in lines if l.startswith("//!")]
    items = []
    docs, attrs, impl = [], [], None
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if IMPL.match(line):
            impl, docs, attrs = line.rstrip(" {"), [], []
        elif line == "}":
            impl = None
        if stripped.startswith("///"):
            docs.append(line)
        elif stripped.startswith("#["):
            attrs.append(line)
        elif BODY_ITEM.match(line):
            items.append(docs + body(lines, i))
            i += len(items[-1]) - len(docs)
            docs, attrs = [], []
            continue
        elif SIG_ITEM.match(line) and (docs or not line.startswith(" ")):
            sig = signature(lines, i)
            if line.startswith(" ") and impl:
                if items and items[-1][0] == impl + " {":
                    items[-1][-1:] = [""] + docs + sig + ["}"]
                else:
                    items.append([impl + " {"] + docs + sig + ["}"])
            else:
                items.append(docs + sig)
            i += len(sig)
            docs, attrs = [], []
            continue
        elif stripped and not stripped.startswith("//"):
            docs, attrs = [], []
        i += 1
    return module_docs, items


def demote(text, levels, hide_doctest_lines=False):
    """Push Markdown headings down `levels` levels, outside code fences.

    With `hide_doctest_lines`, also drop the `# `-prefixed lines rustdoc
    hides inside Rust code blocks.
    """
    out, fence = [], None
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            fence = None if fence else (line.strip()[3:] or "rust")
            out.append(line)
        elif fence is None and line.startswith("#"):
            out.append("#" * levels + line)
        elif hide_doctest_lines and fence and fence.split(",")[0] in ("rust", "no_run", "ignore") and (
            line.strip() == "#" or line.strip().startswith("# ")
        ):
            continue
        else:
            out.append(line)
    return "\n".join(out)


def section(title, text):
    return f"\n\n# {title}\n\n{text.strip()}\n"


def main():
    parts = [
        "# sindr: full reference for LLMs\n\n"
        "> Generated by `scripts/gen_llms_full.py` from the repository sources. "
        "Don't edit by hand. The short index is `llms.txt`.\n"
    ]
    for title, rel in [
        ("Workspace README", "README.md"),
        ("Crate `sindr` README", "sindr/README.md"),
        ("Crate `sindr-devices` README", "sindr-devices/README.md"),
        ("Scope and limitations", "LIMITATIONS.md"),
    ]:
        parts.append(section(f"{title} ({rel})", demote((ROOT / rel).read_text(), 1)))

    for crate in ["sindr", "sindr-devices"]:
        src = ROOT / crate / "src"
        # Private top-level modules (`mod x;` in lib.rs) aren't API.
        private = set(re.findall(r"^mod (\w+);", (src / "lib.rs").read_text(), re.M))
        text = []
        for path in sorted(src.rglob("*.rs")):
            if path.relative_to(src).parts[0].removesuffix(".rs") in private:
                continue
            module_docs, items = api(path)
            if not module_docs and not items:
                continue
            rel = path.relative_to(ROOT)
            text.append(f"## `{rel}`\n")
            if module_docs:
                text.append(demote("\n".join(module_docs), 2, hide_doctest_lines=True).strip() + "\n")
            if items:
                text.append("```rust\n" + "\n\n".join("\n".join(it) for it in items) + "\n```\n")
        parts.append(section(f"Public API of `{crate}`", "\n".join(text)))

    examples = []
    for path in sorted((ROOT / "sindr" / "examples").glob("*.rs")):
        rel = path.relative_to(ROOT)
        examples.append(f"## `{rel}`\n\n```rust\n{path.read_text().rstrip()}\n```\n")
    parts.append(section("Examples", "\n".join(examples)))

    generated = "".join(parts)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != generated:
            print("llms-full.txt is stale: run python3 scripts/gen_llms_full.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
