#!/usr/bin/env python3
"""Regenerate the accuracy tables from the ngspice golden tests.

Runs `cargo test -p sindr --all-features --test golden` with
SINDR_ACCURACY set, so each case records its worst error against ngspice
(see `Check` in sindr/tests/golden.rs). Then it writes:

- docs/ACCURACY.md: every case, its worst error and what it's held to
- README.md, between the accuracy markers: the worst case per analysis

Usage: python3 scripts/accuracy_table.py [--from FILE]

--from reads a file a previous run wrote instead of running the tests.
Errors vary in their last digits between machines, so the tables round
them to one significant figure, and CI doesn't check that they're current.
Rerun this after adding a golden or changing a model.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
FULL = ROOT / "docs" / "ACCURACY.md"
START = "<!-- accuracy:start -->"
END = "<!-- accuracy:end -->"

ANALYSES = [
    ("op_", "Operating point"),
    ("dc_", "DC sweep"),
    ("temp_", "Temperature sweep"),
    ("ac_", "AC"),
    ("cv_", "Diode charge (AC)"),
    ("noise_", "Noise"),
    ("tran_", "Transient"),
]


def analysis(case):
    for prefix, name in ANALYSES:
        if case.startswith(prefix):
            return name
    return "Other"


def sig(x):
    """One significant figure, as 3e-9."""
    if x == 0:
        return "0"
    mant, exp = f"{x:.0e}".split("e")
    return f"{mant}e{int(exp)}"


def pct(x):
    if x == 0:
        return "0 %"
    if x < 1e-5:
        return "< 0.001 %"
    return f"{x * 100:.2g} %"


def fmt(entry, unit):
    err, allowed = entry
    if unit == "rel":
        return sig(err), sig(allowed)
    if unit == "fs":
        return pct(err) + " FS", pct(allowed) + " FS"
    return sig(err) + "°", sig(allowed) + "°"


def cells(rec):
    worst, allowed = [], []
    for unit in ("rel", "fs", "deg"):
        if unit in rec:
            w, a = fmt(rec[unit], unit)
            worst.append(w)
            allowed.append(a)
    return " · ".join(worst), " · ".join(allowed)


def run_tests():
    fd, path = tempfile.mkstemp(suffix=".jsonl")
    os.close(fd)
    env = dict(os.environ, SINDR_ACCURACY=path)
    subprocess.run(
        ["cargo", "test", "-q", "-p", "sindr", "--all-features", "--test", "golden"],
        cwd=ROOT,
        env=env,
        check=True,
    )
    return path


def load(path):
    records = {}
    for line in Path(path).read_text().splitlines():
        rec = json.loads(line)
        prev = records.get(rec["case"])
        if prev is None:
            records[rec["case"]] = rec
            continue
        # A test that checks a case twice: keep the worst of each unit.
        for unit in ("rel", "fs", "deg"):
            if unit in rec and (unit not in prev or rec[unit][0] > prev[unit][0]):
                prev[unit] = rec[unit]
    return records


def full_table(records):
    lines = [
        "# Accuracy against ngspice",
        "",
        "Generated by `scripts/accuracy_table.py` from `sindr/tests/golden.rs`;",
        "don't edit by hand. Each case is a circuit solved by both sindr and",
        "ngspice 47 (see `sindr/tests/golden/README.md`). **Worst** is sindr's",
        "largest deviation over every quantity and point the case checks;",
        "**held to** is the tolerance the test fails beyond.",
        "",
        "- A plain number is a relative error: |sindr − ngspice| / |ngspice|,",
        "  with a floor near zero.",
        "- `% FS` is a transient's error as a share of the waveform's full scale.",
        "- `°` is an AC phase error.",
        "",
        "| Case | Analysis | Worst | Held to |",
        "|---|---|---|---|",
    ]
    order = {name: i for i, (_, name) in enumerate(ANALYSES)}
    for case in sorted(records, key=lambda c: (order.get(analysis(c), 99), c)):
        worst, allowed = cells(records[case])
        lines.append(f"| `{case}` | {analysis(case)} | {worst} | {allowed} |")
    return "\n".join(lines) + "\n"


def summary(records):
    by = {}
    for case, rec in records.items():
        by.setdefault(analysis(case), []).append(rec)
    lines = [
        "| Analysis | Cases | Worst relative error | Worst other |",
        "|---|---|---|---|",
    ]
    for _, name in ANALYSES:
        recs = by.get(name)
        if not recs:
            continue
        rel = max((r["rel"][0] for r in recs if "rel" in r), default=None)
        other = []
        fs = max((r["fs"][0] for r in recs if "fs" in r), default=None)
        deg = max((r["deg"][0] for r in recs if "deg" in r), default=None)
        if fs is not None:
            other.append(pct(fs) + " of full scale")
        if deg is not None:
            other.append(sig(deg) + "° phase")
        lines.append(
            f"| {name} | {len(recs)} | {sig(rel) if rel is not None else '—'} | "
            f"{', '.join(other) or '—'} |"
        )
    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    path = args[1] if args[:1] == ["--from"] else run_tests()
    records = load(path)
    if not records:
        sys.exit("no golden results recorded")
    FULL.write_text(full_table(records))
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit(f"README.md has no {START} … {END} block")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f"{head}{START}\n{summary(records)}\n{END}{tail}")
    print(f"{len(records)} cases → {FULL.relative_to(ROOT)} and README.md")


if __name__ == "__main__":
    main()
